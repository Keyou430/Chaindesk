        "DIAGNOSTICS_CHANGED" -> "状态已变化，请重新预览诊断后再导出。"
        "DIAGNOSTICS_EXPORT_FAILED" -> "诊断导出失败，请重新选择保存位置。"
        else -> "操作未完成，请检查配置或断开后重试。"
    }
}
